#!/usr/bin/env node
/**
 * generate-frontend-types.mjs
 *
 * Parses schema.prisma and generates frontend-safe TS interfaces.
 * Does NOT use prisma generate (that's for backend).
 *
 * Usage:
 *   node generate-frontend-types.mjs [--schemaPath <path>] [--outputPath <path>] [--dry-run]
 *
 * Exit codes: 0 = success, 1 = error
 */

import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { resolve, join, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { buildResult, printResult, exitFromResult, exitFromResultGuarded, findProjectRoot } from "../../_shared/script-utils.mjs";

const __dirname = fileURLToPath(new URL(".", import.meta.url));

const args = process.argv.slice(2);
let schemaPath = null;
let outputPath = null;
let dryRun = false;
for (let i = 0; i < args.length; i++) {
  if (args[i] === "--schemaPath" && args[i + 1]) schemaPath = resolve(args[++i]);
  else if (args[i] === "--outputPath" && args[i + 1]) outputPath = resolve(args[++i]);
  else if (args[i] === "--dry-run") dryRun = true;
}

const root = findProjectRoot(__dirname);
if (!schemaPath) {
  schemaPath = root ? join(root, "apps", "api", "prisma", "schema.prisma") : resolve(process.cwd(), "apps/api/prisma/schema.prisma");
}
if (!outputPath) {
  outputPath = root ? join(root, "packages", "shared-types", "src", "generated.ts") : resolve(process.cwd(), "packages/shared-types/src/generated.ts");
}

const issues = [];

if (!existsSync(schemaPath)) {
  issues.push({ severity: "error", check: "schema-missing", msg: `schema.prisma not found at ${schemaPath}` });
  const result = buildResult(issues);
  printResult(result, "Prisma → Frontend Types Generator");
  exitFromResultGuarded(result);
}

const schema = readFileSync(schemaPath, "utf8");

// Parse models
const modelRegex = /model\s+(\w+)\s*\{([^}]*)\}/g;
const enumRegex = /enum\s+(\w+)\s*\{([^}]*)\}/g;

const enums = new Map();
let enumMatch;
while ((enumMatch = enumRegex.exec(schema)) !== null) {
  const enumName = enumMatch[1];
  const values = enumMatch[2]
    .split("\n")
    .map((l) => l.trim())
    .filter((l) => l && !l.startsWith("//"));
  enums.set(enumName, values);
}

const models = new Map();
let modelMatch;
while ((modelMatch = modelRegex.exec(schema)) !== null) {
  const modelName = modelMatch[1];
  const body = modelMatch[2];
  const fields = [];
  for (const line of body.split("\n")) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith("//") || trimmed.startsWith("@@")) continue;
    // Match: fieldName Type? @...
    const fieldMatch = trimmed.match(/^(\w+)\s+(\w+)(\?)?\s*(?:@.*)?$/);
    if (fieldMatch) {
      const [, name, type, optional] = fieldMatch;
      fields.push({ name, type, optional: Boolean(optional) });
    }
  }
  models.set(modelName, fields);
}

// Map Prisma type → TS type
function mapType(prismaType) {
  const scalarMap = {
    String: "string", Int: "number", BigInt: "string", Boolean: "boolean",
    Float: "number", Decimal: "string", DateTime: "string", Json: "unknown",
    Bytes: "string",
  };
  if (scalarMap[prismaType]) return scalarMap[prismaType];
  if (enums.has(prismaType)) return prismaType; // enum union type
  if (models.has(prismaType)) return prismaType; // relation type
  // Array relation: Type[]
  return prismaType;
}

// Generate TS
let output = `// AUTO-GENERATED by prisma-frontend-types skill. Do not edit manually.\n`;
output += `// Generated from: ${schemaPath}\n\n`;

// Enums
for (const [enumName, values] of enums) {
  output += `export type ${enumName} =\n`;
  for (const v of values) {
    output += `  | "${v}"\n`;
  }
  output += `;\n\n`;
}

// Models as interfaces
for (const [modelName, fields] of models) {
  output += `export interface ${modelName} {\n`;
  for (const field of fields) {
    // Skip soft-delete and internal fields
    if (field.name === "deletedAt" || field.name.startsWith("_")) continue;
    // Skip relation backref fields (fields without scalar type and not in enums/models as scalar)
    const isRelation = !field.type.match(/^(String|Int|BigInt|Boolean|Float|Decimal|DateTime|Json|Bytes)$/) && (models.has(field.type) || enums.has(field.type));
    const tsType = mapType(field.type);
    const optionalMark = field.optional ? "?" : "";
    output += `  ${field.name}${optionalMark}: ${tsType};\n`;
  }
  output += `}\n\n`;
}

issues.push({ severity: "info", check: "types-generated", msg: `Generated ${enums.size} enums + ${models.size} interfaces${dryRun ? " (dry-run, not written)" : ""}` });

if (!dryRun) {
  const outDir = dirname(outputPath);
  if (!existsSync(outDir)) {
    issues.push({ severity: "warning", check: "output-dir-missing", msg: `Output dir ${outDir} does not exist. Create it first.` });
  } else {
    writeFileSync(outputPath, output, "utf8");
    issues.push({ severity: "info", check: "file-written", msg: `Written to ${outputPath}` });
  }
} else {
  console.log("\n--- Generated Types (dry-run) ---\n");
  console.log(output.substring(0, 2000));
  if (output.length > 2000) console.log("... (truncated)");
}

const result = buildResult(issues);
printResult(result, "Prisma → Frontend Types Generator");
exitFromResultGuarded(result);
